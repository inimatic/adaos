"""Project strict widget input schemas into Client; --check never writes files."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/adaos/abi/webui.v1.schema.json"
TARGET = ROOT / "src/adaos/integrations/adaos-client/src/app/runtime/widget-input-contract.generated.ts"
INPUT_DEFINITIONS = {
    "visual.imageCompare": "imageCompareInputs",
    "layout.group": "groupInputs",
    "feedback.taskProgress": "taskProgressInputs",
}


def render() -> str:
    definitions = json.loads(SOURCE.read_text(encoding="utf-8"))["$defs"]
    contracts = {widget: definitions[definition] for widget, definition in INPUT_DEFINITIONS.items()}
    data_contracts = {name: json.loads((SOURCE.parent / filename).read_text(encoding="utf-8")) for name, filename in {
        "adaos.image_annotations.v1": "image.annotations.v1.schema.json",
        "adaos.ui.task_progress.v1": "ui.task_progress.v1.schema.json",
    }.items()}
    canonical = json.dumps([contracts, data_contracts], sort_keys=True, separators=(",", ":"))
    digest = hashlib.sha256(canonical.encode()).hexdigest()
    return (
        "// Generated by scripts/generate_ui_widget_inputs.py; do not edit.\n"
        f"export const WIDGET_INPUT_CONTRACT_DIGEST = 'sha256:{digest}'\n"
        "export const WIDGET_INPUT_CONTRACTS: Record<string, any> = "
        + json.dumps(contracts, ensure_ascii=False, indent=2) + "\n"
        + "export const WIDGET_DATA_CONTRACTS: Record<string, any> = " + json.dumps(data_contracts, ensure_ascii=False, indent=2) + "\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != rendered:
            raise SystemExit("Client widget input contract is stale; run scripts/generate_ui_widget_inputs.py")
        print("Client widget input contract is current")
    else:
        TARGET.write_text(rendered, encoding="utf-8")
        print(f"Generated {TARGET.relative_to(ROOT)}")
