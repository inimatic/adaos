"""Swappable provider port. Credentials never cross the Core boundary."""
from __future__ import annotations

from threading import Event
from typing import Any, Iterator, Protocol


class AIProvider(Protocol):
    def status(self) -> dict[str, Any]: ...
    def models(self, refresh: bool = False) -> list[dict[str, Any]]: ...
    def binding_ref(self) -> str: ...
    def start(self) -> dict[str, Any]: ...
    def cancel_sign_in(self) -> dict[str, Any]: ...
    def verify(self) -> dict[str, Any]: ...
    def disconnect(self) -> dict[str, Any]: ...
    def stream(self, model: str, inputs: list, instructions: str, cancelled: Event,
               **options: Any) -> Iterator[str]: ...
